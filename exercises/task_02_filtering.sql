Задача: отобразить поля с названием пиццы, датой, номером недели и радиусом пиццы для заказов соответствующих одному из двух условий. 
Первое - цена пиццы меньше 30 баллов, а радиус больше 37 см. 
Второе — радиус пиццы больше или равен 35 см, а цена больше 35 баллов.

SELECT name,
       date,
       EXTRACT(WEEK FROM date) AS number_of_week,
       radius
FROM pizza
WHERE price < 30 AND radius > 37
OR (radius >= 35 AND price > 35);
