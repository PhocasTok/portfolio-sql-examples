Задача: посчитайте, сколько хот-догов заказывали с кетчупом и без него. 
Сгруппируйте данные по полю ketchup таблицы hotdog и суммируйте значения в поле quantity.
Требование условия: «суммируйте значения в поле quantity».
Решение: GROUP BY ketchup + SUM(quantity).
Почему нет COUNT(*): в задаче просили именно сумму количества, а не число строк.
Почему нет лишних колонок: по правилам GROUP BY в SELECT можно только поля из GROUP BY и агрегатные функции — иначе запрос не пройдёт валидацию.

SELECT ketchup,
       SUM(quantity) AS total_quantity
FROM hotdog
GROUP BY ketchup;
